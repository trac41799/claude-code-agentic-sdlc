"""benchv2.report — aggregate artifacts into the protocol report (R1-R10)."""
import json
import pathlib

from . import costs

LIMITS = ("Declared limits: N=5 detects effect size ~2xIQR separation; "
          "unmeasured: longevity, team-scale usage, LLM drift across months.")


def render(art_dir: pathlib.Path, out_md: pathlib.Path) -> str:
    runs = json.loads((art_dir / "runs" / "runs.json").read_text(encoding="utf-8"))
    lines = ["# Benchmark V2 report (protocol: docs/specs/002-benchmark-v2/spec.md)", ""]
    # R1 stats per arm
    cells = {}
    for case in sorted({r["case"] for r in runs}):
        for arm in sorted({r["arm"] for r in runs}):
            vals = [float(r["wall_min"]) for r in runs
                    if r["case"] == case and r["arm"] == arm]
            if not vals:
                continue
            cells[(case, arm)] = vals
    if cells:
        lines.append("## Wall time by case/arm (replicates)")
        lines.append("| case | arm | n | median | IQR | min | max |")
        lines.append("|---|---|---|---|---|---|---|")
        for (case, arm), vals in sorted(cells.items()):
            from . import stats as st
            s = st.summarize(vals)
            lines.append(f"| {case} | {arm} | {s['n']} | {s['median']:.1f} | "
                         f"{s['iqr']:.1f} | {s['min']:.1f} | {s['max']:.1f} |")
        lines.append("")
        # significance: framework arm vs bare per case
        lines.append("## Significance (Mann-Whitney, bare vs framework)")
        lines.append("| case | p-value | note |")
        lines.append("|---|---|---|")
        for case in sorted({c for c, _ in cells}):
            if (case, "B") in cells and (case, "A") in cells:
                from . import stats as st
                p = st.mann_whitney(cells[(case, "B")], cells[(case, "A")])
                lines.append(f"| {case} | {p:.4f} | {'significant @0.05' if p < 0.05 else 'NOT significant'} |")
        lines.append("")
    # R2 cost basis
    lines.append("## Cost (R2) — tokens primary, basis labeled")
    lines.append("| case | arm | rep | in | out | cache_read | basis | cents/k |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for r in runs:
        b = r.get("cost_breakdown") or {}
        lines.append(f"| {r['case']} | {r['arm']} | {r['rep']} | {b.get('in')} | "
                     f"{b.get('out')} | {b.get('cache_read')} | {b.get('basis')} | {b.get('cents_k')} |")
    lines.append("")
    # R3 hidden rubric
    lines.append("## Held-out rubric (R3)")
    lines.append("| case | arm | rep | hidden_passed | ok |")
    lines.append("|---|---|---|---|---|---|")
    for r in runs:
        j = r.get("judge") or {}
        lines.append(f"| {r['case']} | {r['arm']} | {r['rep']} | {j.get('hidden_passed')} | {j.get('hidden_ok')} |")
    lines.append("")
    # R7 process
    lines.append("## Process (R7)")
    lines.append("| case | arm | rep | terminal | errors | turns | spawned | compute_min | wall_min |")
    lines.append("|---|---|---|---|---|---|---|---|---|")
    for r in runs:
        p = r.get("process") or {}
        lines.append(f"| {r['case']} | {r['arm']} | {r['rep']} | {p.get('terminal')} | "
                     f"{p.get('errors')} | {p.get('turns')} | {p.get('spawned')} | "
                     f"{p.get('compute_min')} | {p.get('wall_min')} |")
    lines.append("")
    lines.append(LIMITS)
    lines.append("")
    lines.append("*Generated by benchv2.report — regenerable byte-identical from artifacts.*")
    text = "\n".join(lines)
    pathlib.Path(out_md).write_text(text, encoding="utf-8")
    return text