#!/usr/bin/env python3
"""Validate the deck's benchmark claims against the bundled evidence.

Reruns every acceptance gate inside each bundled project and asserts the
passed-count matches the claim in the deck's evidence summary. Exit 0 =
all claims reproduce; writes validation-report.md.

Usage: python evidence/validate.py
"""
import json
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).parent
GF = HERE / "greenfield"
SESS = HERE / "sessions"

# claim -> (project dir, test command, expected passed)
CLAIMS = {
    "be": {
        "A": ("be-a", "python -m pytest tests/ -q", 24),
        "B": ("be-b", "python -m pytest tests/ -q", 22),
        "W": ("be-wave", "python -m pytest tests/ -q", 19),
    },
    "e2e": {
        "A": ("e2e-a", "python -m pytest tests/ -q", 17),
        "B": ("e2e-b", "python -m pytest tests/ -q", 13),
        "W": ("e2e-wave", "python -m pytest tests/ -q", 13),
    },
    "fe": {
        "A": ("fe-a", "node --test tests/", 22),
        "B": ("fe-b", "node --test tests/", 24),
        "W": ("fe-wave", "node --test tests/", 16),
    },
    "db": {
        "A": ("db-a", "python -m pytest tests/ -q", 6),
        "B": ("db-b", "python -m pytest tests/ -q", 8),
        "W": ("db-wave", "python -m pytest tests/ -q", 7),
    },
}


def count_passed(proj: str, cmd: str) -> int:
    r = subprocess.run(cmd, cwd=GF / proj, capture_output=True, text=True,
                       shell=True, timeout=900)
    out = (r.stdout or "") + (r.stderr or "")
    m = re.search(r"(\d+)\s+passed", out) or re.search(r"pass (\d+)", out)
    if not m:
        raise RuntimeError(f"{proj}: no pass count in: {out[-200:]}")
    return int(m.group(1))


def main():
    rows, ok = [], True
    for case, arms in sorted(CLAIMS.items()):
        for arm, (proj, cmd, wanted) in sorted(arms.items()):
            try:
                got = count_passed(proj, cmd)
                good = got == wanted
            except Exception as e:
                got, good = f"ERR: {e}", False
            ok = ok and good
            rows.append((case, arm, proj, wanted, got, "PASS" if good else "FAIL"))
    with open(HERE / "validation-report.md", "w", encoding="utf-8") as f:
        f.write("# Validation report — benchmark claims vs bundled evidence\n\n")
        f.write("Generated by `evidence/validate.py`. Each row reruns the acceptance\n"
                "gate in the bundled project and compares pass counts to the claim.\n\n")
        f.write("| Case | Arm | Project | Claimed | Reproduced | Verdict |\n|---|---|---|---|---|---|\n")
        for case, arm, proj, wanted, got, verdict in rows:
            f.write(f"| {case} | {arm} | {proj} | {wanted} | {got} | {verdict} |\n")
        f.write(f"\n**Overall: {'ALL CLAIMS REPRODUCE' if ok else 'MISMATCHES FOUND'}\n")
    print(f"{'case':<5}{'arm':<4}{'claimed':<9}{'got':<9}{'verdict':<7}")
    print("-" * 34)
    for case, arm, proj, wanted, got, verdict in rows:
        print(f"{case:<5}{arm:<4}{str(wanted):<9}{str(got):<9}{verdict:<7}")
    print(f"\nRESULT: {'ALL CLAIMS REPRODUCE' if ok else 'MISMATCHES FOUND'}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())